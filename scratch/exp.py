print('verify dir delete:', idx.verify_against_full_rescan())
os.makedirs(os.path.join(pkg,'sub'))
w('sub/__init__.py','import sys\n')
w('sub/mod.py','import os\n')
idx.apply_changes([os.path.join(pkg,'sub','__init__.py'), os.path.join(pkg,'sub','mod.py')])

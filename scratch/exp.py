import os, sys, tempfile, shutil
sys.path.insert(0, os.getcwd())
from import_tracker.index import IncrementalIndex
work = tempfile.mkdtemp()
pkg = os.path.join(work, 'mylib')
os.makedirs(os.path.join(pkg, 'sub'))
def w(rel, text):
    with open(os.path.join(pkg, rel), 'w', encoding='utf-8') as f: f.write(text)
w('__init__.py', 'import os\nfrom .sub import a\n')
w('sub/__init__.py', 'from . import mod\n')
w('sub/mod.py', 'import json as j\nimport json as json2\nfrom .. import sub\nfrom .... import nope\ntry:\n    import yaml\nexcept ImportError:\n    pass\n')
idx = IncrementalIndex(pkg, 'mylib')
idx.cold_start()
print('verify cold:', idx.verify_against_full_rescan())
os.remove(os.path.join(pkg,'sub','mod.py'))
idx.apply_changes([os.path.join(pkg,'sub','mod.py')])
print('verify delete:', idx.verify_against_full_rescan())
w('sub/mod.py', 'import csv\n')
idx.apply_changes([os.path.join(pkg,'sub','mod.py')])
print('verify recreate:', idx.verify_against_full_rescan())
for n in range(5):
    w('sub/mod.py', f'import time as t{n}\n')
    idx.apply_changes([os.path.join(pkg,'sub','mod.py')])
print('verify repeated edits:', idx.verify_against_full_rescan())

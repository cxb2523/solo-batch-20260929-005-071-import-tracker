s = idx.snapshot()
print('stale:', s['groups']['mylib.sub.mod']['stale'], 'retained:', s['groups']['mylib.sub.mod']['imports'])
print('verify stale:', idx.verify_against_full_rescan())
w('sub/mod.py', 'import csv\n')
idx.apply_changes([os.path.join(pkg,'sub','mod.py')])
print('verify recovered:', idx.verify_against_full_rescan())
shutil.rmtree(os.path.join(pkg,'sub'))
